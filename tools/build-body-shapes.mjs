// Builds src/app/shared/components/body-map/body-shapes.ts, the body map's figures, from
// react-native-body-highlighter (MIT, see LICENSE-body-highlighter.txt beside it), at a
// pinned commit so the shapes only change when this script does.
//
//     node tools/build-body-shapes.mjs
//
// The upstream files are TypeScript, but they're only read as text: each body part's slug
// and its SVG path strings are picked out, and nothing downloaded is run.

import { writeFileSync } from 'node:fs';

const COMMIT = '8ed39ac2ae9cb46fb79d77eedec7e5b029a75174';
const BASE = `https://raw.githubusercontent.com/HichamELBSI/react-native-body-highlighter/${COMMIT}`;
const OUT = new URL('../src/app/shared/components/body-map/body-shapes.ts', import.meta.url);

// Their slugs to our muscle groups (src/app/models/exercise.ts); the rest are drawn but
// never shaded
const MUSCLES = {
    chest: 'chest',
    deltoids: 'shoulders',
    biceps: 'biceps',
    triceps: 'triceps',
    forearm: 'forearms',
    abs: 'abs',
    obliques: 'obliques',
    trapezius: 'traps',
    'upper-back': 'upper-back',
    'lower-back': 'lower-back',
    gluteal: 'glutes',
    abductors: 'abductors',
    adductors: 'adductors',
    quadriceps: 'quads',
    hamstring: 'hamstrings',
    calves: 'calves',
    tibialis: 'shins',
    neck: 'neck',
};
const NOT_MUSCLES = new Set(['head', 'hair', 'hands', 'feet', 'knees', 'ankles']);

const FIGURES = {
    male: {
        wrapper: 'components/SvgMaleWrapper.tsx',
        front: { file: 'assets/bodyFront.ts', viewBox: '0 0 724 1448' },
        back: { file: 'assets/bodyBack.ts', viewBox: '724 0 724 1448' },
    },
    female: {
        wrapper: 'components/SvgFemaleWrapper.tsx',
        front: { file: 'assets/bodyFemaleFront.ts', viewBox: '-50 -40 734 1538' },
        back: { file: 'assets/bodyFemaleBack.ts', viewBox: '756 0 774 1448' },
    },
};

async function get(path) {
    const response = await fetch(`${BASE}/${path}`);
    if (!response.ok) {
        throw new Error(`${path}: ${response.status}`);
    }
    return response.text();
}

const isPath = (text) => /^[Mm][\d\s.,\-a-zA-Z]+$/.test(text);

/** Each body part's slug and its paths (left, right and common together), in file order. */
function readParts(text) {
    const starts = [...text.matchAll(/slug:\s*"([a-z-]+)"/g)];
    return starts.map((match, i) => {
        const block = text.slice(match.index, starts[i + 1]?.index ?? text.length);
        const paths = [...block.matchAll(/"([^"]+)"/g)].map((m) => m[1]).filter(isPath);
        const slug = match[1];
        if (!(slug in MUSCLES) && !NOT_MUSCLES.has(slug)) {
            throw new Error(`Unknown slug ${slug}`);
        }
        return { muscle: MUSCLES[slug] ?? null, paths };
    });
}

/** The outline of each side, front then back, as the wrapper draws them. */
function readOutlines(text) {
    const outlines = [...text.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]).filter(isPath);
    if (outlines.length !== 2) {
        throw new Error(`Expected 2 outlines, found ${outlines.length}`);
    }
    return { front: outlines[0], back: outlines[1] };
}

const figures = {};
for (const [figure, { wrapper, front, back }] of Object.entries(FIGURES)) {
    const outlines = readOutlines(await get(wrapper));
    figures[figure] = {};
    for (const [side, { file, viewBox }] of Object.entries({ front, back })) {
        figures[figure][side] = {
            viewBox,
            outline: outlines[side],
            shapes: readParts(await get(file)),
        };
    }
}

writeFileSync(
    OUT,
    `// Generated by tools/build-body-shapes.mjs: don't edit by hand.
// The shapes are from react-native-body-highlighter by ELABBASSI Hicham (MIT), commit
// ${COMMIT.slice(0, 12)}; its licence is in LICENSE-body-highlighter.txt beside this file.

import { BodyFigure, MuscleGroup } from '../../../models/exercise';

/** One shape on a figure: a muscle group's paths, or a part that's never shaded (null). */
export interface BodyShape {
    muscle: MuscleGroup | null;
    paths: readonly string[];
}

export interface BodySide {
    viewBox: string;
    outline: string;
    shapes: readonly BodyShape[];
}

export const BODY_FIGURES: Record<BodyFigure, Record<'front' | 'back', BodySide>> = ${JSON.stringify(figures)};
`
);
console.log(`Wrote ${OUT.pathname}`);
